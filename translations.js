let currentLang = 'de';
try {
  const savedLang = localStorage.getItem('dbd_tournament_app_v3_lang');
  if (savedLang && TRANSLATIONS[savedLang]) {
    currentLang = savedLang;
  }
} catch (e) {
  currentLang = 'de';
}

function t(key, fallback = '') {
  const dict = TRANSLATIONS[currentLang] || TRANSLATIONS.de;
  if (dict && dict[key] !== undefined) {
    return dict[key];
  }
  const defaultDict = TRANSLATIONS.de;
  if (defaultDict && defaultDict[key] !== undefined) {
    return defaultDict[key];
  }
  return fallback || key;
}

function getCurrentLanguage() {
  return currentLang;
}

function setLanguage(lang) {
  if (!TRANSLATIONS[lang]) return;
  currentLang = lang;
  try {
    localStorage.setItem('dbd_tournament_app_v3_lang', lang);
  } catch (e) {
    // ignore
  }

  // Update language buttons active state
  document.querySelectorAll('.lang-btn').forEach(btn => {
    btn.classList.toggle('active', btn.dataset.lang === lang);
  });

  // Re-translate all static elements with data-i18n
  applyStaticTranslations();

  // If app is loaded, trigger re-render of dynamic components
  if (typeof renderAll === 'function') {
    renderAll();
  }
}

function applyStaticTranslations() {
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.dataset.i18n;
    el.textContent = t(key, el.textContent);
  });

  document.querySelectorAll('[data-i18n-html]').forEach(el => {
    const key = el.dataset.i18nHtml;
    el.innerHTML = t(key, el.innerHTML);
  });

  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.dataset.i18nPlaceholder;
    el.placeholder = t(key, el.placeholder);
  });

  document.querySelectorAll('[data-i18n-title]').forEach(el => {
    const key = el.dataset.i18nTitle;
    el.title = t(key, el.title);
  });
}
